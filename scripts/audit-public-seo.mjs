import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const appRoot = path.join(root, "altftoolweb/src/app");
const reportPath = path.join(root, "docs/seo-route-inventory.md");
const pagePattern = /^page\.(?:js|jsx|ts|tsx)$/;
const layoutNames = ["layout.js", "layout.jsx", "layout.ts", "layout.tsx"];
const writeReport = process.argv.includes("--write");

function relative(file) {
  return path.relative(root, file).split(path.sep).join("/");
}

async function collectPages(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const pages = [];

  for (const entry of entries) {
    if (entry.name === "node_modules" || entry.name === ".next") continue;

    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      pages.push(...(await collectPages(absolute)));
    } else if (pagePattern.test(entry.name)) {
      pages.push(absolute);
    }
  }

  return pages;
}

function routeFromPage(pageFile) {
  const relativeDirectory = path.relative(appRoot, path.dirname(pageFile));
  const segments = relativeDirectory
    .split(path.sep)
    .filter(Boolean)
    .filter((segment) => !(segment.startsWith("(") && segment.endsWith(")")))
    .filter((segment) => !segment.startsWith("@"));

  return segments.length ? `/${segments.join("/")}` : "/";
}

function hasMetadataExport(source) {
  return (
    /\bexport\s+(?:const|let|var)\s+metadata\b/.test(source) ||
    /\bexport\s+(?:async\s+)?function\s+generateMetadata\b/.test(source) ||
    /\bexport\s*\{[^}]*\bmetadata\b[^}]*\}/s.test(source)
  );
}

async function findMetadataSource(pageFile, pageSource) {
  if (hasMetadataExport(pageSource)) {
    return { file: pageFile, source: pageSource };
  }

  for (const layoutName of layoutNames) {
    const layoutFile = path.join(path.dirname(pageFile), layoutName);
    try {
      const source = await readFile(layoutFile, "utf8");
      if (hasMetadataExport(source)) return { file: layoutFile, source };
    } catch {
      // This route has no layout with that extension.
    }
  }

  return null;
}

function metadataStrategy(source = "") {
  if (/\bcreateGeoPageMetadata\s*\(/.test(source)) return "Central geo helper";
  if (/\bcreatePageMetadata\s*\(/.test(source)) return "Central helper";
  if (/\bbuild[A-Z][A-Za-z0-9]*Metadata\s*\(/.test(source)) return "Feature helper";
  return "Raw metadata";
}

function indexingPolicy(source = "") {
  const hasNoIndex =
    /\bnoindex\s*:\s*true\b/.test(source) ||
    /\bindex\s*:\s*false\b/.test(source);

  if (!hasNoIndex) return "Indexable";

  const isConditional =
    /\bgenerateMetadata\b/.test(source) ||
    /\bparams\b/.test(source) ||
    /\bsearchParams\b/.test(source) ||
    /\bnoindex\s*:\s*!/.test(source);

  return isConditional ? "Conditional / noindex" : "Noindex";
}

function groupForRoute(route) {
  if (route === "/") return "Home";
  const firstSegment = route.split("/").filter(Boolean)[0] || "other";
  return firstSegment.startsWith("[") ? "Dynamic fallback" : firstSegment;
}

function rawMetadataFailures(route, source = "") {
  const failures = [];
  const requiredFields = [
    ["title", /\btitle\s*:/],
    ["description", /\bdescription\s*:/],
    ["canonical", /\bcanonical\s*:/],
    ["Open Graph", /\bopenGraph\s*:/],
    ["Twitter", /\btwitter\s*:/],
  ];

  for (const [label, pattern] of requiredFields) {
    if (!pattern.test(source)) {
      failures.push(`${route}: raw indexable metadata is missing ${label}`);
    }
  }

  return failures;
}

function escapeCell(value) {
  return String(value).replace(/\|/g, "\\|").replace(/\n/g, " ");
}

function renderReport(rows) {
  const exactMetadata = rows.filter((row) => row.metadataFile).length;
  const indexable = rows.filter((row) => row.policy === "Indexable").length;
  const conditional = rows.filter((row) => row.policy === "Conditional / noindex").length;
  const noindex = rows.filter((row) => row.policy === "Noindex").length;
  const clientPages = rows.filter((row) => row.clientPage).length;
  const groupCounts = new Map();

  for (const row of rows) {
    groupCounts.set(row.group, (groupCounts.get(row.group) || 0) + 1);
  }

  const groupRows = [...groupCounts.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([group, count]) => `| \`${escapeCell(group)}\` | ${count} |`)
    .join("\n");

  const routeRows = rows
    .map(
      (row) =>
        `| \`${escapeCell(row.route)}\` | ${escapeCell(row.policy)} | ${escapeCell(row.strategy)} | \`${escapeCell(row.metadataFile)}\` | \`${escapeCell(row.pageFile)}\` |`,
    )
    .join("\n");

  return `# AltFTool Public SEO Route Inventory

This file is generated by \`npm run seo:routes:write\`. Do not edit the route table manually.

## Coverage

- Public App Router page patterns: **${rows.length}**
- Routes with an exact page or route-layout metadata source: **${exactMetadata}/${rows.length}**
- Indexable route patterns: **${indexable}**
- Conditional or fallback noindex route patterns: **${conditional}**
- Always-noindex route patterns: **${noindex}**
- Client-rendered page files protected by exact server metadata layouts: **${clientPages}**

Dynamic route patterns can resolve to multiple real URLs. Their metadata generators must return \`noindex\` for invalid, private, preview, redirect-only, or empty states.

## Route Groups

| Group | Page patterns |
|---|---:|
${groupRows}

## Route-Level SEO

| Route pattern | Index policy | Metadata strategy | Exact metadata source | Page file |
|---|---|---|---|---|
${routeRows}
`;
}

const pageFiles = (await collectPages(appRoot)).sort((left, right) =>
  routeFromPage(left).localeCompare(routeFromPage(right)),
);
const rows = [];
const failures = [];

for (const pageFile of pageFiles) {
  const pageSource = await readFile(pageFile, "utf8");
  const route = routeFromPage(pageFile);
  const metadata = await findMetadataSource(pageFile, pageSource);
  const metadataSource = metadata?.source || "";
  const strategy = metadata ? metadataStrategy(metadataSource) : "Missing";
  const policy = metadata ? indexingPolicy(metadataSource) : "Unknown";

  if (!metadata) {
    failures.push(`${route}: no exact page or same-directory layout metadata export`);
  }

  if (/^\s*["']use client["'];?/m.test(pageSource) && !metadata) {
    failures.push(`${route}: client page has no exact server metadata layout`);
  }

  if (metadata && strategy === "Raw metadata" && policy === "Indexable") {
    failures.push(...rawMetadataFailures(route, metadataSource));
  }

  if (/\b(?:canonical|path)\s*:\s*["']https?:\/\/(?:localhost|127\.0\.0\.1)/i.test(metadataSource)) {
    failures.push(`${route}: metadata contains a localhost canonical/path`);
  }

  rows.push({
    route,
    group: groupForRoute(route),
    policy,
    strategy,
    clientPage: /^\s*["']use client["'];?/m.test(pageSource),
    metadataFile: metadata ? relative(metadata.file) : "",
    pageFile: relative(pageFile),
  });
}

const duplicateRoutes = rows
  .map((row) => row.route)
  .filter((route, index, routes) => routes.indexOf(route) !== index);
for (const route of new Set(duplicateRoutes)) {
  failures.push(`${route}: duplicate App Router page pattern`);
}

if (writeReport) {
  await writeFile(reportPath, renderReport(rows), "utf8");
  console.log(`Wrote ${relative(reportPath)}.`);
}

if (failures.length) {
  console.error(`Public SEO audit failed with ${failures.length} issue(s):`);
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

const indexable = rows.filter((row) => row.policy === "Indexable").length;
const protectedRoutes = rows.length - indexable;
console.log(
  `Public SEO audit passed: ${rows.length}/${rows.length} routes have exact metadata (${indexable} indexable, ${protectedRoutes} noindex-aware).`,
);
