import { access, readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { renderBrandMarkSvg } from "../packages/ui/src/brand/brand.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const failures = [];

const paths = {
  tokens: "packages/ui/src/tokens.css",
  styles: "packages/ui/src/styles.css",
  webTokens: "altftoolweb/packages/ui/src/tokens.css",
  webStyles: "altftoolweb/packages/ui/src/styles.css",
  exports: "packages/ui/src/index.jsx",
  webGlobals: "altftoolweb/src/app/globals.css",
  adminGlobals: "altftoolwebadmin/src/app/globals.css",
  webNext: "altftoolweb/next.config.mjs",
  adminNext: "altftoolwebadmin/next.config.mjs",
  webHeader: "altftoolweb/src/platform/navigation/Header.jsx",
  webFooter: "altftoolweb/src/platform/navigation/Footer.jsx",
  adminSidebar: "altftoolwebadmin/src/components/admin/AdminSidebar.jsx",
};

async function read(relativePath) {
  return readFile(path.join(root, relativePath), "utf8");
}

function check(condition, message) {
  if (!condition) failures.push(message);
}

const [
  tokens,
  styles,
  webTokens,
  webStyles,
  uiExports,
  webGlobals,
  adminGlobals,
  webNext,
  adminNext,
  webHeader,
  webFooter,
  adminSidebar,
] = await Promise.all(Object.values(paths).map(read));

const requiredTokens = [
  "--anslation-ds-page",
  "--anslation-ds-surface",
  "--anslation-ds-text",
  "--anslation-ds-muted",
  "--anslation-ds-primary",
  "--anslation-ds-secondary",
  "--anslation-ds-danger",
  "--anslation-ds-focus-ring",
  "--anslation-ds-control-md",
  "--anslation-ds-radius-lg",
  "--anslation-ds-shadow-md",
  "--anslation-ds-motion-base",
];

for (const token of requiredTokens) {
  check(tokens.includes(`${token}:`), `Missing required token: ${token}`);
}

check(
  tokens.includes('html[data-theme="dark"]'),
  "Shared tokens must define a dark theme.",
);
check(
  tokens.includes("@media (prefers-reduced-motion: reduce)"),
  "Shared tokens must honor reduced motion.",
);
check(
  tokens === webTokens,
  "Web and root token sources drifted; keep packages/ui/src/tokens.css synchronized.",
);
check(
  styles === webStyles,
  "Web and root shared styles drifted; keep packages/ui/src/styles.css synchronized.",
);

const rawColorPattern = /#[0-9a-f]{3,8}\b|(?:rgb|hsl)a?\(/gi;
check(
  !rawColorPattern.test(styles),
  "packages/ui/src/styles.css contains raw colors; move values to tokens.css.",
);

const primitiveOverridePattern =
  /--anslation-ds-[a-z0-9-]+\s*:\s*(?:#[0-9a-f]{3,8}\b|(?:rgb|hsl)a?\()/i;
for (const [label, source] of [
  ["web globals", webGlobals],
  ["admin globals", adminGlobals],
]) {
  check(
    !primitiveOverridePattern.test(source),
    `${label} contains a raw --anslation-ds-* override; shared primitives belong in tokens.css.`,
  );
  check(
    source.includes('@import "@altftool/ui/styles.css";'),
    `${label} must import the shared UI stylesheet.`,
  );
}

for (const [label, source] of [
  ["web Next config", webNext],
  ["admin Next config", adminNext],
]) {
  check(
    source.includes("transpilePackages") && source.includes('"@altftool/ui"'),
    `${label} must transpile @altftool/ui.`,
  );
}

const requiredExports = [
  "BrandLogo",
  "BrandMark",
  "Button",
  "IconButton",
  "Input",
  "SearchInput",
  "Toggle",
  "Modal",
  "Alert",
  "PageShell",
  "Tabs",
  "ThemeModeMenu",
  "ThemeModeSelector",
  "ThemeProvider",
  "useThemeMode",
];
for (const component of requiredExports) {
  check(
    new RegExp(`\\b${component}\\b`).test(uiExports),
    `@altftool/ui is missing the ${component} export.`,
  );
}

for (const [label, source, component] of [
  ["web header", webHeader, "BrandLogo"],
  ["web footer", webFooter, "BrandLogo"],
  ["admin sidebar", adminSidebar, "BrandMark"],
]) {
  check(
    source.includes(component) && source.includes("@altftool/ui"),
    `${label} must use the canonical shared ${component}.`,
  );
}

const generatedBanner =
  "<!-- Generated by npm run brand:sync from packages/ui/src/brand/brand.js. -->\n";
const expectedBrandAsset = `${generatedBanner}${renderBrandMarkSvg()}\n`;
const brandTargets = [
  "altftoolweb/public/brand/altftool-mark.svg",
  "altftoolwebadmin/public/brand/altftool-mark.svg",
];
for (const target of brandTargets) {
  const current = await read(target);
  check(
    current === expectedBrandAsset,
    `${target} is stale; run npm run brand:sync.`,
  );
}

const legacyLogoPaths = [
  "altftoolweb/public/assets/altf-header-logo-dark.png",
  "altftoolweb/public/assets/altf-header-logo-generated.png",
  "altftoolweb/public/assets/altf-header-logo.png",
  "altftoolweb/public/assets/altf-mark.png",
  "altftoolweb/public/assets/altf-wordmark.png",
  "altftoolweb/public/assets/altf_white.png",
  "altftoolwebadmin/public/logos/altflogo.png",
];
for (const legacyPath of legacyLogoPaths) {
  try {
    await access(path.join(root, legacyPath));
    failures.push(`Legacy duplicate logo still exists: ${legacyPath}`);
  } catch {
    // Expected: canonical assets are generated under public/brand.
  }
}

if (failures.length > 0) {
  console.error("Design-system check failed:");
  failures.forEach((failure) => console.error(`- ${failure}`));
  process.exitCode = 1;
} else {
  console.log(
    "Design-system check passed: tokens, themes, exports, shells, and brand assets are aligned.",
  );
}
