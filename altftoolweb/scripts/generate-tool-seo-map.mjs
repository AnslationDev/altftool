#!/usr/bin/env node
/**
 * Collects per-tool SEO content into generated shards.
 *
 * Each tool may ship its own `src/tools/<slug>/seo.js`:
 *
 *   const seo = {
 *     intro: "…",
 *     useCases: ["…", "…", "…"],
 *     benefits: [["Title", "body"], …],
 *     faqs: [["Question", "Answer"], …],
 *   };
 *   export default seo;
 *
 * Why per-tool files instead of one hand-edited map: the catalogue is growing
 * into the thousands, and tools are authored in parallel batches. A single
 * shared file means every author edits the same lines — merge conflicts and,
 * worse, one bad edit corrupts the SEO of every tool. A file per tool is
 * isolated, reviewable in a diff, and deleted along with its tool.
 *
 * Output is sharded so no generated file grows unbounded; the barrel re-exports
 * one merged object. Legacy content in toolContentOverrides.js is untouched and
 * still wins nothing/loses nothing — the consumer checks per-tool first.
 */
import fs from "node:fs";
import path from "node:path";

const TOOLS_DIR = "src/tools";
const OUT_DIR = "src/app/tools/generated";
const SHARD_SIZE = 400;

const slugs = fs
  .readdirSync(TOOLS_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("_"))
  .map((d) => d.name)
  .filter((slug) => fs.existsSync(path.join(TOOLS_DIR, slug, "seo.js")))
  .sort();

fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });

const HEADER = "// AUTO-GENERATED by scripts/generate-tool-seo-map.mjs — do not edit.\n// Source of truth: src/tools/<slug>/seo.js\n\n";

const shardCount = Math.max(1, Math.ceil(slugs.length / SHARD_SIZE));

for (let i = 0; i < shardCount; i += 1) {
  const chunk = slugs.slice(i * SHARD_SIZE, (i + 1) * SHARD_SIZE);
  const imports = chunk
    .map((slug, j) => `import s${j} from "@/tools/${slug}/seo";`)
    .join("\n");
  const entries = chunk
    .map((slug, j) => `  ${JSON.stringify(slug)}: s${j},`)
    .join("\n");
  fs.writeFileSync(
    path.join(OUT_DIR, `toolSeoShard${i}.js`),
    `${HEADER}${imports}\n\nexport default {\n${entries}\n};\n`,
  );
}

const barrelImports = Array.from(
  { length: shardCount },
  (_, i) => `import shard${i} from "./toolSeoShard${i}";`,
).join("\n");
const barrelSpread = Array.from(
  { length: shardCount },
  (_, i) => `  ...shard${i},`,
).join("\n");

fs.writeFileSync(
  path.join(OUT_DIR, "toolSeoMap.js"),
  `${HEADER}${barrelImports}\n\nexport const generatedToolSeo = {\n${barrelSpread}\n};\n\nexport default generatedToolSeo;\n`,
);

console.log(
  `✅ toolSeoMap generated (${slugs.length} tools, ${shardCount} shard${shardCount === 1 ? "" : "s"})`,
);
