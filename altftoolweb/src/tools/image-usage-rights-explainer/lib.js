/**
 * Image usage rights explainer.
 *
 * Pure module: no DOM, no React, no clock, no randomness. The same answers
 * always produce the same checklist.
 *
 * This is an informational decision aid, not legal advice. It applies the
 * general structure of copyright, licence terms, personality rights and
 * trademark law, and flags where a lawyer or the rights holder has to be
 * involved. Specific outcomes vary by country and by the exact wording of the
 * licence you hold.
 *
 * Rules referenced:
 *  - Copyright subsists in a photograph from creation; using it needs the
 *    owner's permission unless a licence or a statutory exception applies.
 *  - Indian Copyright Act 1957, s.52(1)(s) and s.52(1)(t): a painting, drawing
 *    or photograph of a work of architecture, or of a sculpture or other
 *    artistic work permanently situated in a public place, is not an
 *    infringement. Freedom of panorama is narrower or absent in many other
 *    countries.
 *  - Indian Copyright Act 1957, s.57: the author keeps moral rights, including
 *    the right to object to distortion or mutilation, even after assigning
 *    the copyright.
 *  - Creative Commons 4.0: NC forbids commercial use, ND forbids sharing
 *    adaptations, SA requires adaptations under the same licence, and BY
 *    requires attribution in every case.
 *  - Personality and publicity rights are separate from copyright, so a public
 *    domain photograph of a recognisable person still needs a model release
 *    for advertising use.
 */

