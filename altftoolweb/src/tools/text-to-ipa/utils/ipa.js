// Consonant clusters and digraphs that should be treated as units for the rule-based fallback.
const VOWELS = "aeiou";

function isVowel(ch) {
  return VOWELS.includes(ch);
}

// Approximate, last-resort IPA for words not in the dictionary.
// This is intentionally simple: it maps common English patterns to plausible
// IPA and is clearly flagged as an estimate in the UI.
function estimateIpa(word) {
  const w = word.toLowerCase();
  let out = "";

  // Silent 'e' at the end handling
  let i = 0;
  while (i < w.length) {
    const ch = w[i];
    const next = w[i + 1] || "";
    const next2 = w[i + 2] || "";
    const prev = w[i - 1] || "";

    if (ch === "c" && next === "h") {
      out += "tʃ";
      i += 2;
      continue;
    }
    if (ch === "s" && next === "h") {
      out += "ʃ";
      i += 2;
      continue;
    }
    if (ch === "t" && next === "h") {
      out += "θ";
      i += 2;
      continue;
    }
    if (ch === "p" && next === "h") {
      out += "f";
      i += 2;
      continue;
    }
    if (ch === "w" && next === "h") {
      out += "w";
      i += 2;
      continue;
    }
    if (ch === "g" && next === "h") {
      out += "g";
      i += 2;
      continue;
    }

    if (".,!?;:\"'()[]{}"-includes(ch)) {
      i += 1;
      continue;
    }

    switch (ch) {
      case "a":
        out += next === "r" ? "ɑr" : "æ";
        break;
      case "e":
        out += next === "r" ? "ɜr" : "ɛ";
        break;
      case "i":
        out += next === "e" ? "i" : next === "o" ? "aɪ" : next === "g" && next2 === "h" ? "aɪ" : "ɪ";
        break;
      case "o":
        out += next === "o" ? "u" : next === "u" ? "aʊ" : next === "r" ? "ɔr" : "ɑ";
        break;
      case "u":
        out += next === "r" ? "ɜr" : "ʌ";
        break;
      case "y":
        out += isVowel(prev) ? "i" : "aɪ";
        break;
      case "b":
        out += "b";
        break;
      case "d":
        out += "d";
        break;
      case "f":
        out += "f";
        break;
      case "g":
        out += "g";
        break;
      case "h":
        out += "h";
        break;
      case "j":
        out += "dʒ";
        break;
      case "k":
        out += "k";
        break;
      case "l":
        out += "l";
        break;
      case "m":
        out += "m";
        break;
      case "n":
        out += "n";
        break;
      case "p":
        out += "p";
        break;
      case "q":
        out += "kw";
        i += 1;
        continue;
      case "r":
        out += "r";
        break;
      case "s":
        out += "s";
        break;
      case "t":
        out += "t";
        break;
      case "v":
        out += "v";
        break;
      case "w":
        out += "w";
        break;
      case "x":
        out += "ks";
        break;
      case "z":
        out += "z";
        break;
      default:
        out += ch;
    }
    i += 1;
  }

  // Drop a final silent 'e'
  out = out.replace(/([æɛɪɑʌɔ])e$/, "$1");
  return out;
}

export function wordToIpa(word) {
  if (!word) return { ipa: "", known: false };
  const clean = word.toLowerCase().replace(/[^a-z']/g, "");
  if (!clean) return { ipa: "", known: false };

  if (IPA_DICTIONARY[clean]) {
    return { ipa: IPA_DICTIONARY[clean], known: true };
  }
  return { ipa: estimateIpa(clean), known: false };
}
