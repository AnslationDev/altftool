/**
 * Data portability request generator.
 *
 * GDPR Art. 20 is narrower than most people assume, and this module encodes the
 * three conditions that have to hold at the same time:
 *
 *   1. The lawful basis is consent (Art. 6(1)(a) or Art. 9(2)(a)) or performance
 *      of a contract (Art. 6(1)(b)). Legitimate interests, legal obligation,
 *      public task and vital interests do NOT give a portability right —
 *      Art. 15 access is the fallback in those cases.
 *   2. The processing is carried out by automated means. Paper files are out.
 *   3. The data was "provided by" the data subject. Article 29 Working Party
 *      Guidelines WP242 rev.01 read that as covering data actively supplied
 *      (forms, uploads) and data observed from the person's activity (search
 *      history, traffic and location data, raw device logs), but NOT data the
 *      controller derived or inferred, such as a credit score, a risk rating or
 *      an advertising interest profile.
 *
 * Other provisions used:
 *   - Art. 20(1): the format must be structured, commonly used and machine-readable.
 *   - Art. 20(2): direct controller-to-controller transmission where technically feasible.
 *   - Art. 20(4): portability must not adversely affect the rights of others.
 *   - Art. 12(3): reply within one calendar month, extendable by two further months.
 *   - Art. 12(5): free of charge.
 *   - Cal. Civ. Code s.1798.100(d): the export must be in a portable and, to the
 *     extent technically feasible, readily useable format that lets the consumer
 *     transmit it to another entity, answered within 45 days under s.1798.130(a)(2).
 *   - India's DPDP Act, 2023 contains a right to access information (s.11) and to
 *     correction and erasure (s.12), but no standalone portability right, so a
 *     request there is framed as an access request in a machine-readable format.
 */

const ISO_PATTERN = /^\d{4}-\d{2}-\d{2}$/;

