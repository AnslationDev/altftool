const round = (value, places = 0) => {
  const factor = 10 ** places;
  return Math.round(value * factor) / factor;
};

/** Index of an element in the generating cycle, or -1. */
export function elementIndex(element) {
  return ELEMENTS.indexOf(element);
}

/** The element this one feeds in the generating cycle. */
export function generates(element) {
  const i = elementIndex(element);
  return i < 0 ? null : ELEMENTS[(i + 1) % ELEMENTS.length];
}

/** The element that controls this one. */
export function controlledBy(element) {
  const i = elementIndex(element);
  return i < 0 ? null : ELEMENTS[(i + ELEMENTS.length - 2) % ELEMENTS.length];
}

/**
 * How element `a` stands to element `b`.
 * Returns one of: same, a-generates-b, a-controls-b, b-controls-a, b-generates-a.
 */
export function elementRelationship(a, b) {
  const ia = elementIndex(a);
  const ib = elementIndex(b);
  if (ia < 0 || ib < 0) return null;
  const step = (ib - ia + ELEMENTS.length) % ELEMENTS.length;
  if (step === 0) return "same";
  if (step === 1) return "a-generates-b";
  if (step === 2) return "a-controls-b";
  if (step === 3) return "b-controls-a";
  return "b-generates-a";
}

/**
 * The mediating element for a controlling pair: the one that the controller
 * feeds and that in turn feeds the controlled element. Only defined when `a`
 * controls `b`.
 */
export function mediatingElement(a, b) {
  if (elementRelationship(a, b) !== "a-controls-b") return null;
  return generates(a);
}

/** Bagua area for a Black Sect grid cell (row 1-3 from the door wall). */
export function baguaByGrid(row, col) {
  const r = Number(row);
  const c = Number(col);
  if (!Number.isInteger(r) || !Number.isInteger(c) || r < 1 || r > 3 || c < 1 || c > 3) return null;
  return BAGUA.find((area) => area.gridRow === r && area.gridCol === c) || null;
}

/**
 * Guidance for one room sitting in one bagua area.
 *
 * @param {object} input
 * @param {string} input.room    one of ROOMS ids
 * @param {string} input.area    one of BAGUA ids
 * @returns {object} { error } or the guidance
 */
export function roomGuidance({ room, area } = {}) {
  const space = ROOMS.find((r) => r.id === room);
  if (!space) return { error: "Choose which room you are looking at." };
  const zone = BAGUA.find((b) => b.id === area);
  if (!zone) return { error: "Choose which bagua area of the plan the room falls in." };

  const roomElement = space.element;
  const areaElement = zone.element;
  const relation = elementRelationship(roomElement, areaElement);

  let harmony = "neutral";
  let harmonyLabel = "";
  let advice = "";
  let mediator = null;

  if (relation === "same") {
    harmony = "aligned";
    harmonyLabel = `Both the room and the area are ${ELEMENT_INFO[areaElement].label}`;
    advice = `The room and its position agree. Use the ${ELEMENT_INFO[areaElement].label.toLowerCase()} palette confidently, but add a little of the ${ELEMENT_INFO[generates(areaElement)].label.toLowerCase()} it feeds so a single element does not dominate the whole space.`;
  } else if (relation === "a-generates-b") {
    harmony = "supportive";
    harmonyLabel = `${ELEMENT_INFO[roomElement].label} feeds ${ELEMENT_INFO[areaElement].label}`;
    advice = `The room's activity nourishes the life area it sits in. Lead with the ${ELEMENT_INFO[areaElement].label.toLowerCase()} colours of the area and keep the ${ELEMENT_INFO[roomElement].label.toLowerCase()} of the room as the supporting accent.`;
  } else if (relation === "b-generates-a") {
    harmony = "supportive";
    harmonyLabel = `${ELEMENT_INFO[areaElement].label} feeds ${ELEMENT_INFO[roomElement].label}`;
    advice = `The position nourishes the room. Lead with the ${ELEMENT_INFO[roomElement].label.toLowerCase()} colours of the room and use the area's ${ELEMENT_INFO[areaElement].label.toLowerCase()} as the grounding second colour.`;
  } else if (relation === "a-controls-b") {
    harmony = "clash";
    mediator = mediatingElement(roomElement, areaElement);
    harmonyLabel = `${ELEMENT_INFO[roomElement].label} controls ${ELEMENT_INFO[areaElement].label}`;
    advice = `The room's element works against the life area it occupies. The traditional fix is not to remove either but to bring in ${ELEMENT_INFO[mediator].label} — it is fed by ${ELEMENT_INFO[roomElement].label.toLowerCase()} and in turn feeds ${ELEMENT_INFO[areaElement].label.toLowerCase()}, so it turns the conflict into a chain. Keep strong ${ELEMENT_INFO[roomElement].label.toLowerCase()} colours to accents here.`;
  } else {
    harmony = "clash";
    mediator = mediatingElement(areaElement, roomElement);
    harmonyLabel = `${ELEMENT_INFO[areaElement].label} controls ${ELEMENT_INFO[roomElement].label}`;
    advice = `The position works against the room's activity. Introduce ${ELEMENT_INFO[mediator].label}, which ${ELEMENT_INFO[areaElement].label.toLowerCase()} feeds and which in turn feeds ${ELEMENT_INFO[roomElement].label.toLowerCase()}, and keep the area's own colours to accents rather than covering whole walls.`;
  }

  // Lead colour: the area's element whenever the room already feeds, matches or
  // (per the advice above) has to stand down in favour of it — i.e. every
  // relation except "b-generates-a" and "b-controls-a", where the room's own
  // element leads instead. Support and Reduce are then picked per relation so
  // that all three slots are always three distinct elements — see the a-controls-b
  // and b-controls-a cases below, where naively reusing the generic rules made
  // Lead and Reduce (or Support and the promised "area's own colour") collide.
  const leadElement =
    relation === "a-generates-b" || relation === "same" || relation === "a-controls-b"
      ? areaElement
      : roomElement;

  let supportElement;
  if (relation === "same") {
    supportElement = generates(areaElement);
  } else if (relation === "a-generates-b") {
    // Lead is the area's element here, so the room's own element is the support.
    supportElement = roomElement;
  } else if (relation === "b-generates-a") {
    // Lead is the room's own element here, so the area's element supports it.
    supportElement = areaElement;
  } else if (relation === "a-controls-b") {
    // The room's element is being pushed down to an accent (see reduceElement
    // below), so the mediator being introduced is the supporting colour.
    supportElement = mediator;
  } else {
    // b-controls-a: the mediator is the colour being introduced to break the
    // clash, so it takes the supporting slot (mirrors how a-controls-b puts
    // its mediator in supportElement above).
    supportElement = mediator;
  }

  // Reduce ("keep to accents only"): the aggressor element, pushed down to an
  // accent. In a-controls-b that's the room's own element, which is exactly
  // what controlledBy(areaElement) resolves to (the element controlling the
  // area). In b-controls-a the aggressor is the area's own element instead,
  // so it must be used directly rather than re-deriving it via controlledBy.
  const reduceElement = relation === "b-controls-a" ? areaElement : controlledBy(areaElement);

  return {
    roomId: space.id,
    roomLabel: space.label,
    roomElement,
    roomElementLabel: ELEMENT_INFO[roomElement].label,
    roomIsYin: space.yin,
    rules: space.rules,
    areaId: zone.id,
    trigram: zone.trigram,
    lifeArea: zone.life,
    areaElement,
    areaElementLabel: ELEMENT_INFO[areaElement].label,
    areaDirection: zone.direction,
    areaGrid: `row ${zone.gridRow} from the door wall, column ${zone.gridCol} from the left`,
    areaNote: zone.note,
    relation,
    harmony,
    harmonyLabel,
    advice,
    mediator,
    mediatorLabel: mediator ? ELEMENT_INFO[mediator].label : null,
    leadElement,
    leadColours: ELEMENT_INFO[leadElement].colours,
    supportElement,
    supportColours: ELEMENT_INFO[supportElement].colours,
    reduceElement,
    reduceElementLabel: ELEMENT_INFO[reduceElement].label,
    reduceColours: ELEMENT_INFO[reduceElement].colours,
    shape: ELEMENT_INFO[leadElement].shape,
    materials: ELEMENT_INFO[leadElement].materials,
    quality: ELEMENT_INFO[leadElement].quality,
    percentLead: LEAD_SHARE,
    percentSupport: SUPPORT_SHARE,
    percentRest: round(100 - LEAD_SHARE - SUPPORT_SHARE),
  };
}
