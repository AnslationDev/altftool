/**
 * Feng shui room, element and bagua reference.
 *
 * Feng shui is a traditional Chinese practice, not a measurable science.
 * Everything here is a record of what the tradition holds, set out so it can be
 * applied consistently rather than piecemeal.
 *
 * The computational part is the five-element (wu xing) cycle, which is a
 * closed system and therefore exact.
 *
 * GENERATING CYCLE (sheng): Wood feeds Fire, Fire makes Earth (ash), Earth
 * yields Metal, Metal carries Water (condensation), Water grows Wood. Listing
 * the elements in that order makes "generates" the next index and "is
 * generated by" the previous index.
 *
 * CONTROLLING CYCLE (ke): Wood breaks Earth, Earth dams Water, Water quenches
 * Fire, Fire melts Metal, Metal cuts Wood. In the same ordering that is
 * exactly two steps forward, so:
 *
 *   relationship(a, b) is decided by (index(b) - index(a)) mod 5
 *     0 = same element
 *     1 = a generates b
 *     2 = a controls b
 *     3 = b controls a
 *     4 = b generates a
 *
 * MEDIATION. When one element controls another the traditional remedy is not
 * to remove either but to introduce the element that sits between them in the
 * generating cycle, because it is fed by the controller and in turn feeds the
 * controlled element. If a controls b, that mediator is at index(a) + 1. Wood
 * controlling Earth is softened by Fire; Water quenching Fire is softened by
 * Wood.
 *
 * THE BAGUA. The eight trigrams plus the centre, mapped onto a plan. Two
 * schools place it differently and both are given: the classical (compass)
 * school anchors each trigram to a compass direction, while the Black Sect
 * (BTB) school lays a three-by-three grid over the plan with the bottom row on
 * the wall containing the main door.
 */

